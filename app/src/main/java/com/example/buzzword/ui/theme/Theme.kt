package com.example.buzzword.ui.theme

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.foundation.shape.RoundedCornerShape
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Shapes
import androidx.compose.material3.darkColorScheme
import androidx.compose.material3.lightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

private val LightColors = lightColorScheme(
    primary = Orange, onPrimary = Color.White,
    primaryContainer = OrangeContainer, onPrimaryContainer = OnOrangeContainer,
    secondary = Ink, onSecondary = Color.White,
    secondaryContainer = InkContainer, onSecondaryContainer = Ink,
    background = Paper, onBackground = TextMain,
    surface = Paper, onSurface = TextMain,
    surfaceVariant = PaperHigh, onSurfaceVariant = TextMuted,
    surfaceContainerLowest = Color.White,
    surfaceContainerLow = PaperLow,
    surfaceContainer = PaperMid,
    surfaceContainerHigh = PaperHigh,
    surfaceContainerHighest = PaperHighest,
    outline = TextMuted, outlineVariant = OutlineLight,
)

private val DarkColors = darkColorScheme(
    primary = OrangeDark, onPrimary = OnOrangeDark,
    primaryContainer = OrangeContainerDark, onPrimaryContainer = OnOrangeContainerDark,
    secondary = InkDark, onSecondary = Ink,
    secondaryContainer = InkContainerDark, onSecondaryContainer = InkContainer,
    background = Night, onBackground = TextMainDark,
    surface = Night, onSurface = TextMainDark,
    surfaceVariant = NightHigh, onSurfaceVariant = TextMutedDark,
    surfaceContainerLowest = NightLowest,
    surfaceContainerLow = NightLow,
    surfaceContainer = NightMid,
    surfaceContainerHigh = NightHigh,
    surfaceContainerHighest = NightHighest,
    outline = TextMutedDark, outlineVariant = OutlineDark,
)

/** Rounder corners everywhere: cards, buttons, text fields. */
private val BuzzwordShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(24.dp),
    extraLarge = RoundedCornerShape(32.dp),
)

/** Our own colors (not the phone's), so the app looks the same on every phone. */
@Composable
fun BuzzwordTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = Typography, // from Type.kt, generated by Android Studio
        shapes = BuzzwordShapes,
        content = content,
    )
}